void OLED_ShowChar(uint8_t x, uint8_t line, char c) {
    uint8_t idx = c - ' ';
    if (idx >= sizeof(F8x16)/sizeof(F8x16[0])) idx = 0;
    uint8_t page = line * 2;

    
    OLED_SetPos(x, page);
    for (uint8_t i = 0; i < 8; i++) WriteData(F8x16[idx][i]);

    OLED_SetPos(x, page + 1);
    for (uint8_t i = 0; i < 8; i++) WriteData(F8x16[idx][i + 8]);
}

void OLED_ShowString(uint8_t x, uint8_t line, char *str) {
    while (*str) {
        OLED_ShowChar(x, line, *str);
        x += 8;
        str++;
    }
}

void OLED_Init(void) {
    HAL_Delay(100);
    WriteCmd(0xAE);
    WriteCmd(0xD5); WriteCmd(0x80);
    WriteCmd(0xA8); WriteCmd(0x3F);
    WriteCmd(0xD3); WriteCmd(0x00);
    WriteCmd(0x40);
    WriteCmd(0x8D); WriteCmd(0x14); // 电荷泵升压
    WriteCmd(0x20); WriteCmd(0x02);
    WriteCmd(0xA1); // 左右
    WriteCmd(0xC8); // 上下
    WriteCmd(0xDA); WriteCmd(0x12);
    WriteCmd(0x81); WriteCmd(0xCF);
    WriteCmd(0xD9); WriteCmd(0xF1);
    WriteCmd(0xDB); WriteCmd(0x40);
    WriteCmd(0xA4);
    WriteCmd(0xA6);
    OLED_Clear();
    WriteCmd(0xAF);
}