#include "oled.h"

#define OLED_ADDR 0x78

#define SCL_H() HAL_GPIO_WritePin(GPIOB, GPIO_PIN_10, GPIO_PIN_SET)
#define SCL_L() HAL_GPIO_WritePin(GPIOB, GPIO_PIN_10, GPIO_PIN_RESET)
#define SDA_H() HAL_GPIO_WritePin(GPIOB, GPIO_PIN_11, GPIO_PIN_SET)
#define SDA_L() HAL_GPIO_WritePin(GPIOB, GPIO_PIN_11, GPIO_PIN_RESET)

static void I2C_Delay(void) {
    for (volatile int i = 0; i < 20; i++);
}

static void I2C_Start(void) {
    SDA_H(); SCL_H(); I2C_Delay();
    SDA_L(); I2C_Delay();
    SCL_L(); I2C_Delay();
}

static void I2C_Stop(void) {
    SDA_L(); SCL_H(); I2C_Delay();
    SDA_H(); I2C_Delay();
}

static void I2C_Send(uint8_t b) {
    for (int i = 0; i < 8; i++) {
        if (b & 0x80) SDA_H(); else SDA_L();
        b <<= 1;
        I2C_Delay();
        SCL_H(); I2C_Delay();
        SCL_L(); I2C_Delay();
    }
    SDA_H(); I2C_Delay();
    SCL_H(); I2C_Delay();
    SCL_L(); I2C_Delay();
}

static void WriteCmd(uint8_t cmd) {
    I2C_Start();
    I2C_Send(OLED_ADDR);
    I2C_Send(0x00);
    I2C_Send(cmd);
    I2C_Stop();
}

static void WriteData(uint8_t dat) {
    I2C_Start();
    I2C_Send(OLED_ADDR);
    I2C_Send(0x40);
    I2C_Send(dat);
    I2C_Stop();
}

void OLED_SetPos(uint8_t x, uint8_t page) {
    WriteCmd(0xB0 + page);
    WriteCmd(((x & 0xF0) >> 4) | 0x10);
    WriteCmd(x & 0x0F);
}

void OLED_Clear(void) {
    for (uint8_t i = 0; i < 8; i++) {
        OLED_SetPos(0, i);
        for (uint8_t j = 0; j < 128; j++) WriteData(0x00);
    }
}

